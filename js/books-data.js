// ==========================================================================
// Catálogo de libros — ÚNICA fuente de datos de producto para toda la web.
// Se usa en: categoria.html (listado/filtros/buscador), producto.html
// (ficha dinámica) e index.html (destacados).
//
// Para añadir un libro nuevo: copia un objeto, cambia el "id" (debe ser
// único, sin espacios) y rellena sus campos. No hace falta tocar más
// archivos: aparecerá solo en el catálogo, en el buscador y en su propia
// ficha de producto (producto.html?id=tu-id).
//
// Campos opcionales de la ficha técnica (se muestran solo si existen):
//   finish: 'Brillo' | 'Mate'                → acabado de la cubierta
//   paper: 'Blanco offset' | 'Crema' | 'Blanco semi brillante' (o el que sea)
//   highlights: ['Frase corta 1', 'Frase corta 2', ...] → puntos destacados
//               en viñetas, encima del párrafo de descripción
// ==========================================================================

// Devuelve la ruta .webp de una portada (mismo nombre, sin la extensión
// .jpg). Todas las portadas tienen ya su copia .webp generada en /img
// (más ligera). Si por lo que sea faltara esa copia, el atributo
// onerror="" de cada <img> hace que el navegador recupere el .jpg original
// automáticamente, así que esto nunca puede dejar una portada rota.
window.toWebp = function (coverPath) {
  return coverPath.replace(/\.jpg$/i, '.webp');
};

// ---- Idioma del libro → código de idioma HTML (atributo lang) -------------
// Todo el catálogo es en español hoy, pero la categoría "Otros idiomas" del
// menú está pensada para cuando añadas ediciones en otras lenguas. Cuando
// llegue ese día, basta con poner el "idioma" correspondiente en el libro
// (ej. idioma: 'Inglés') y el título/descripción de ese libro se marcarán
// automáticamente con el lang="en" correcto — así un lector de pantalla lo
// pronuncia bien y Google entiende que ese contenido concreto no es español.
// (Esto NO es lo mismo que "hreflang": hreflang enlaza páginas completas que
// son traducción una de otra; aquí es un único catálogo con libros sueltos
// en distintos idiomas, así que lo correcto es marcar el idioma por libro
// con "lang", no con etiquetas hreflang a nivel de página.)
window.IDIOMA_LANG = {
  'Español': 'es', 'Inglés': 'en', 'Portugués': 'pt', 'Francés': 'fr', 'Italiano': 'it'
};
window.idiomaToLang = function (idioma) {
  return window.IDIOMA_LANG[idioma] || 'es';
};

// ---- Aviso de stock (opcional) --------------------------------------------
// Por defecto ningún libro lleva control de stock (igual que hasta ahora:
// no aparece ningún aviso). Si para un libro en concreto quieres avisar de
// que quedan pocas unidades o que se ha agotado, añádele el campo "stock"
// con el número de ejemplares que quedan:
//   stock: 3   → se muestra "Últimas 3 unidades" y se puede seguir comprando
//   stock: 0   → se muestra "Agotado" y se desactiva el botón de comprar
// Si no pones "stock", el libro se comporta exactamente igual que siempre.
window.STOCK_LOW_THRESHOLD = 5;
window.stockInfo = function (book) {
  if (typeof book.stock !== 'number') return null;
  if (book.stock <= 0) return { estado: 'agotado', texto: 'Agotado' };
  if (book.stock <= window.STOCK_LOW_THRESHOLD) {
    return { estado: 'poco', texto: book.stock === 1 ? 'Última unidad' : 'Últimas ' + book.stock + ' unidades' };
  }
  return { estado: 'ok', texto: '' };
};

// ---- Portadas alternativas del MISMO libro (opcional) ---------------------
// Algunos títulos existen con dos diseños de cubierta distintos. Es el
// MISMO libro (mismo texto, mismo precio): lo único que cambia es la
// portada, así que NO se crean dos productos, sino un solo libro con un
// array "covers":
//
//   covers: [
//     { style: 'ilustrada',   file: 'img/mi-libro.jpg' },
//     { style: 'tipografica', file: 'img/mi-libro-tipografica.jpg' }
//   ]
//
// Con eso, automáticamente:
//   · en el catálogo y la home, la tarjeta va alternando las portadas
//     sola cada pocos segundos (js/cover-carousel.js);
//   · en la ficha, el cliente elige con qué portada quiere el libro y esa
//     elección viaja al pedido ("Tapa blanda … · Portada ilustrada").
// El primer elemento del array es la portada por defecto y debe coincidir
// con el campo "cover" de siempre (que se sigue usando para SEO/Open Graph).
